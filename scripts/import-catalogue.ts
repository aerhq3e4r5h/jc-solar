// Import the product spreadsheet into Supabase.
//
//   npm run catalogue:import -- <file.xlsx>                 preview only (default)
//   npm run catalogue:import -- <file.xlsx> --apply         save to Supabase
//   npm run catalogue:import -- <file.xlsx> --sql seed.sql  write a SQL seed file
//   npm run catalogue:import -- <file.xlsx> --report r.json write the full report
//
// --apply needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in the environment
// (e.g. from .env.local). Products are matched on SKU, so running it again
// with an updated spreadsheet updates prices and stock instead of duplicating.

import { createClient } from "@supabase/supabase-js";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { buildImport } from "../src/lib/catalogue/build-import";
import { buildPayload, formatReport, type ImportOutcome } from "../src/lib/catalogue/payload";
import { planImport, type ExistingProduct } from "../src/lib/catalogue/plan";
import { readCatalogueFile } from "../src/lib/catalogue/workbook";
import type { Database } from "../src/lib/supabase/database.types";

function loadEnvFile(path: string) {
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}

function arg(flag: string): string | undefined {
  const i = process.argv.indexOf(flag);
  return i > -1 ? process.argv[i + 1] : undefined;
}

async function main() {
  loadEnvFile(".env.local");
  loadEnvFile(".env");
  const file = process.argv.slice(2).find((a) => !a.startsWith("--") && a !== arg("--sql") && a !== arg("--report"));
  if (!file) {
    console.error("Usage: npm run catalogue:import -- <file.xlsx|file.csv> [--apply] [--sql out.sql] [--report out.json]");
    process.exit(1);
  }
  const apply = process.argv.includes("--apply");
  const data = readFileSync(file);
  const sha = createHash("sha256").update(data).digest("hex");

  const read = await readCatalogueFile(data, file);
  console.log(`File: ${basename(file)}`);
  for (const s of read.sheets) console.log(`  sheet "${s.name}": ${s.rows} rows`);
  if (!read.ok) {
    console.error(`\n${read.error}`);
    process.exit(1);
  }
  console.log(`Using sheet "${read.sheetUsed}"\n`);

  const build = buildImport(read.rows);
  const payload = buildPayload(build, basename(file), sha);

  const url = process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  const supabase = url && key ? createClient<Database>(url, key, { auth: { persistSession: false } }) : null;

  if (supabase) {
    const { data: rows, error } = await supabase
      .from("products")
      .select("sku, name, price_incl_vat, stock_qty, allow_backorder, brands(name), categories(slug)");
    if (error) throw new Error(`Could not read current catalogue: ${error.message}`);
    const existing: ExistingProduct[] = (rows ?? []).map((r) => ({
      sku: r.sku,
      name: r.name,
      brand: r.brands?.name ?? null,
      category: r.categories?.slug ?? "",
      priceInclVat: Number(r.price_incl_vat),
      stockQty: r.stock_qty,
      allowBackorder: r.allow_backorder,
    }));
    const plan = planImport(build.products, existing);
    console.log(`Against the live catalogue: ${plan.counts.insert} new, ${plan.counts.update} changed, ${plan.counts.unchanged} unchanged`);
    if (plan.notInFile.length) console.log(`${plan.notInFile.length} products in the shop are not in this file (left as they are)`);
    console.log("");
  }

  let outcome: ImportOutcome | undefined;
  if (apply) {
    if (!supabase) {
      console.error("--apply needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY");
      process.exit(1);
    }
    if (build.products.length === 0) {
      console.error("Nothing valid to import.");
      process.exit(1);
    }
    const { data: result, error } = await supabase.rpc("import_catalogue", { p_payload: payload });
    if (error) throw new Error(`Import failed and nothing was saved: ${error.message}`);
    outcome = result as unknown as ImportOutcome;
  }

  console.log(formatReport(build, outcome));

  const sqlOut = arg("--sql");
  if (sqlOut) {
    const json = JSON.stringify(payload);
    if (json.includes("$import$")) throw new Error("Payload contains the SQL quote marker");
    writeFileSync(
      sqlOut,
      `-- Generated by scripts/import-catalogue.ts from ${basename(file)} (sha256 ${sha.slice(0, 12)})\n` +
        `select public.import_catalogue($import$${json}$import$::jsonb);\n`,
    );
    console.log(`\nWrote ${sqlOut}`);
  }
  const reportOut = arg("--report");
  if (reportOut) {
    writeFileSync(reportOut, JSON.stringify({ ...payload.report, totals: build.totals, outcome }, null, 2));
    console.log(`Wrote ${reportOut}`);
  }
  if (!apply && !sqlOut) console.log("\nPreview only. Run again with --apply to save.");
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
